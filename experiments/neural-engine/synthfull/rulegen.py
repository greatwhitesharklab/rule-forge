"""Random causal rule generator for CLAB-full (the anti-observer-bias core).

CLAB-lite's rules were hand-written, so the experiment designer knew the
answer. Here the ground-truth rule pool is generated by a seeded RNG: the
seed decides the content, and NOBODY (including the author of this code)
needs to see it. Blind discipline: no concrete generated rule content may
be referenced in code, comments, tests, or docs — tests assert statistical
properties only.

A rule is a conjunction of 1-3 conditions drawn from three condition
sources, plus a random logit effect:

  * "num": observable field, tail comparison ("observable > q" or "< q"),
    threshold calibrated on a pilot sample drawn by the generator itself;
  * "cat": categorical field, membership in a small value set drawn with
    frequency-weighted probabilities (so fire rates stay non-degenerate);
  * "seq": sequence statistic (e.g. a paste-count style aggregate), tail
    comparison, threshold calibrated on a pilot sample.

Effects: magnitude ~ U(weight_mag_range), sign positive with probability
`pos_weight_prob`; regime drift mutates weights later (decay/boost/flip,
same modes as CLAB-lite) — categorical and sequence rules drift too.

Human-readable text is produced by templates (condition -> Chinese phrase).
The full pool is JSON-serializable via `rules_payload` for downstream
ground-truth consumers (grader adaptation is out of scope here).

Fixed RNG draw order: pilot factors -> pilot observables -> pilot sequences
-> pilot categoricals -> per rule (condition count -> kinds -> fields ->
thresholds/values -> weight), with rejection redraws on degenerate pilot
fire rates. Do not reorder.
"""

from __future__ import annotations

import json
from dataclasses import asdict, dataclass
from typing import Any, Literal

import numpy as np

from synthfull.config import FullConfig
from synthfull.factors import observe_factors, sample_factors
from synthfull.sequences import SEQ_STAT_INDEX, sample_sequences, seq_stats

EXPERIENCE = "experience"
HELDOUT = "heldout"

COND_NUM = "num"
COND_CAT = "cat"
COND_SEQ = "seq"
_KINDS = (COND_NUM, COND_CAT, COND_SEQ)

# Human-readable field labels for the text templates (mechanism metadata,
# not rule content).
NUM_CN: dict[str, str] = {
    "income_volatility_obs": "收入波动",
    "debt_to_income_obs": "负债收入比",
    "credit_history_years_reported": "信用历史年限",
    "delinquencies_reported": "申报逾期次数",
    "months_employed": "在职月数",
    "savings_months_obs": "储蓄覆盖月数",
    "requested_loan_to_income": "申请额度收入比",
    "platform_loans_disclosed": "申报借贷平台数",
}
SEQ_CN: dict[str, str] = {
    "seq_len": "行为序列长度",
    "paste_count": "粘贴次数",
    "backspace_count": "回退删除次数",
    "idle_count": "长时间停顿次数",
    "edit_count": "字段修改次数",
    "focus_count": "字段聚焦次数",
    "total_duration": "申请总时长",
    "mean_duration": "平均单步时长",
    "max_duration": "最长单步时长",
    "paste_ratio": "粘贴占比",
}


@dataclass
class FeatureView:
    """Decision-time feature block that rules fire on."""

    observables: np.ndarray  # [n, F] float
    observable_index: dict[str, int]
    categories: dict[str, np.ndarray]  # field name -> [n] int value index
    stats: np.ndarray  # [n, S] sequence statistics
    stat_index: dict[str, int]


@dataclass(frozen=True)
class Condition:
    """One atomic condition; `op` is ">" / "<" (num, seq) or "in" (cat)."""

    kind: Literal["num", "cat", "seq"]
    field: str
    op: Literal[">", "<", "in"]
    threshold: float | None = None
    values: tuple[int, ...] | None = None

    def mask(self, fv: FeatureView) -> np.ndarray:
        if self.kind == COND_CAT:
            return np.isin(fv.categories[self.field], list(self.values or ()))
        col = (fv.observables[:, fv.observable_index[self.field]]
               if self.kind == COND_NUM
               else fv.stats[:, fv.stat_index[self.field]])
        return col > self.threshold if self.op == ">" else col < self.threshold


@dataclass(frozen=True)
class FullRule:
    """Random conjunction -> bad-logit adjustment, with template text.

    `weight` is the BASE weight (regime 0); FullWorld keeps its own mutable
    weight vector for regime drift, FullRule objects stay immutable.
    """

    rule_id: str
    pool: str  # EXPERIENCE | HELDOUT
    conditions: tuple[Condition, ...]
    weight: float  # positive = raises bad logit, negative = lowers it
    text: str

    def fires(self, fv: FeatureView) -> np.ndarray:
        """Boolean mask [n_cases] of cases where all conditions hold."""
        m = np.ones(fv.observables.shape[0], dtype=bool)
        for cond in self.conditions:
            m &= cond.mask(fv)
        return m


class RandomRuleGenerator:
    """Seeded generator of the ground-truth causal rule pool."""

    def __init__(self, config: FullConfig) -> None:
        self.config = config
        self.rng = np.random.Generator(np.random.PCG64(config.seed))
        # Pilot draws calibrate numeric/sequence thresholds against the same
        # distributions the world will sample (deterministic given the seed).
        n = config.pilot_size
        pf = sample_factors(self.rng, config.factors, n)
        pilot_obs = observe_factors(self.rng, config.factors, pf)
        pe, pd, pl, _ = sample_sequences(self.rng, n, config.modes)
        pilot_stats = seq_stats(pe, pd, pl)
        self._obs_names = tuple(f.observable for f in config.factors)
        pilot_cats: dict[str, np.ndarray] = {}
        self._cat_probs = {}
        for spec in config.categoricals:
            ranks = np.arange(1, spec.pool_size + 1, dtype=np.float64)
            p = ranks ** -spec.zipf_alpha
            probs = p / p.sum()
            self._cat_probs[spec.name] = probs
            cdf = np.cumsum(probs)
            idx = np.searchsorted(cdf, self.rng.random(n), side="right")
            pilot_cats[spec.name] = np.minimum(idx, spec.pool_size - 1).astype(np.int32)
        # Pilot FeatureView: used to reject degenerate rules (see _draw_rule).
        self._pilot = FeatureView(
            observables=pilot_obs,
            observable_index={nm: i for i, nm in enumerate(self._obs_names)},
            categories=pilot_cats, stats=pilot_stats, stat_index=SEQ_STAT_INDEX,
        )

    # -- public API --------------------------------------------------------

    def generate(self) -> tuple[FullRule, ...]:
        """The full pool: n_experience rules followed by n_heldout rules."""
        cfg = self.config
        rules: list[FullRule] = []
        for i in range(cfg.n_experience):
            rules.append(self._draw_rule(f"EXP-{i + 1:02d}", EXPERIENCE))
        for i in range(cfg.n_heldout):
            rules.append(self._draw_rule(f"HLD-{i + 1:02d}", HELDOUT))
        return tuple(rules)

    # -- internals ----------------------------------------------------------

    def _draw_rule(self, rule_id: str, pool: str) -> FullRule:
        """Draw one rule, redrawing if its PILOT fire rate is degenerate.

        Acceptance is a purely statistical check (pilot fire rate inside
        [fire_floor, fire_cap]) — it inspects no rule content, so the blind
        discipline holds. Bounded attempts guarantee termination; the final
        candidate is accepted as-is in the pathological case.
        """
        rule = self._draw_candidate(rule_id, pool)
        for _ in range(self.config.max_redraws):
            rate = float(rule.fires(self._pilot).mean())
            if self.config.fire_floor <= rate <= self.config.fire_cap:
                break
            rule = self._draw_candidate(rule_id, pool)
        return rule

    def _draw_candidate(self, rule_id: str, pool: str) -> FullRule:
        cfg, rng = self.config, self.rng
        k = int(rng.choice(3, p=cfg.cond_count_probs)) + 1
        kinds = rng.choice(3, size=k, p=cfg.cond_kind_probs)
        conds: list[Condition] = []
        used: set[tuple[str, str]] = set()
        for kind in kinds:
            cond = self._draw_condition(_KINDS[kind], used)
            if cond is not None:
                conds.append(cond)
        mag = rng.uniform(*cfg.weight_mag_range)
        sign = 1.0 if rng.random() < cfg.pos_weight_prob else -1.0
        weight = sign * mag
        text = self._rule_text(conds, weight)
        return FullRule(rule_id, pool, tuple(conds), float(weight), text)

    def _draw_condition(
        self, kind: str, used: set[tuple[str, str]]
    ) -> Condition | None:
        """Draw one condition; None if no fresh field remains for its kind."""
        rng, cfg = self.rng, self.config
        if kind == COND_NUM:
            field = self._pick_field(self._obs_names, kind, used)
            if field is None:
                return None
            col = self._pilot.observables[:, self._obs_names.index(field)]
            op, thr = self._draw_tail_threshold(col)
            return Condition(COND_NUM, field, op, thr)
        if kind == COND_SEQ:
            names = tuple(SEQ_STAT_INDEX)
            field = self._pick_field(names, kind, used)
            if field is None:
                return None
            col = self._pilot.stats[:, SEQ_STAT_INDEX[field]]
            op, thr = self._draw_tail_threshold(col)
            return Condition(COND_SEQ, field, op, thr)
        # categorical value-set
        names = tuple(s.name for s in cfg.categoricals)
        field = self._pick_field(names, kind, used)
        if field is None:
            return None
        spec = next(s for s in cfg.categoricals if s.name == field)
        size = int(rng.choice(3, p=cfg.cat_set_size_probs)) + 1
        if spec.pool_size > cfg.big_pool_threshold:
            size += cfg.big_pool_bonus
        probs = self._cat_probs[field]
        values = rng.choice(spec.pool_size, size=size, replace=False, p=probs)
        return Condition(COND_CAT, field, "in",
                         values=tuple(int(v) for v in values))

    def _pick_field(
        self, names: tuple[str, ...], kind: str, used: set[tuple[str, str]]
    ) -> str | None:
        """Uniform pick among fields not already used in this rule (no two
        conditions of one rule constrain the same field)."""
        free = [f for f in names if (kind, f) not in used]
        if not free:
            return None
        field = free[int(self.rng.integers(len(free)))]
        used.add((kind, field))
        return field

    def _draw_tail_threshold(self, col: np.ndarray) -> tuple[Literal[">", "<"], float]:
        """Tail comparison with a pilot-calibrated quantile threshold."""
        rng, cfg = self.rng, self.config
        if rng.random() < 0.5:
            return ">", float(np.quantile(col, rng.uniform(*cfg.tail_hi_q)))
        return "<", float(np.quantile(col, rng.uniform(*cfg.tail_lo_q)))

    # -- text templates ------------------------------------------------------

    def _cond_text(self, cond: Condition) -> str:
        if cond.kind == COND_NUM:
            cn = NUM_CN.get(cond.field, cond.field)
            return f"{cn}{'高于' if cond.op == '>' else '低于'}{cond.threshold:.2f}"
        if cond.kind == COND_SEQ:
            cn = SEQ_CN.get(cond.field, cond.field)
            return f"{cn}{'高于' if cond.op == '>' else '低于'}{cond.threshold:.2f}"
        cat_cn = next((s.cn_name for s in self.config.categoricals
                       if s.name == cond.field), cond.field)
        return f"{cat_cn}命中重点值集({len(cond.values or ())}个值)"

    def _rule_text(self, conds: list[Condition], weight: float) -> str:
        body = "且".join(self._cond_text(c) for c in conds)
        degree = "显著" if abs(weight) > 0.6 else ""
        direction = "上升" if weight > 0 else "下降"
        return f"{body}的申请人违约概率{degree}{direction}"


def rules_payload(rules: tuple[FullRule, ...] | list[FullRule]) -> dict[str, Any]:
    """JSON-serializable ground-truth structure (format 'synthfull.rules/v1').

    Mirrors the CLAB-lite ground-truth consumption pattern: pool tag,
    conditions, base weight, and human-readable text per rule. The returned
    structure is JSON-native (lists, not tuples), so a json round-trip is an
    identity.
    """
    out_rules: list[dict[str, Any]] = []
    for r in rules:
        d = asdict(r)
        d["conditions"] = [
            {**c, "values": list(c["values"]) if c["values"] is not None else None}
            for c in d["conditions"]
        ]
        out_rules.append(d)
    return {
        "format": "synthfull.rules/v1",
        "pools": [EXPERIENCE, HELDOUT],
        "rules": out_rules,
    }


def rules_to_json(rules: tuple[FullRule, ...] | list[FullRule]) -> str:
    """Canonical JSON dump (sorted keys) — handy for equality checks."""
    return json.dumps(rules_payload(rules), ensure_ascii=False, sort_keys=True)
